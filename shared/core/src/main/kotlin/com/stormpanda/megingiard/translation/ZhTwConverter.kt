    /**
     * Convert any Chinese input text into standardized Taiwan Traditional Chinese gaming text.
     */
    fun convertToTaiwanTraditional(input: String): String {
        if (input.isBlank()) return input

        var result = input
        for ((simpTerm, tradTerm) in GAMING_TERM_MAP) {
            if (result.contains(simpTerm)) {
                result = result.replace(simpTerm, tradTerm)
            }
        }

        val sb = StringBuilder(result.length)
        for (char in result) {
            val tradChar = SIMPLIFIED_TO_TRADITIONAL[char] ?: char
            sb.append(tradChar)
        }

        return sb.toString()
    }
